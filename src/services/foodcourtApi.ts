const CHANNEL_NAME = 'unugha_foodcourt_realtime_sync_v1';

export const realtimeChannel =
  typeof window !== 'undefined' && 'BroadcastChannel' in window
    ? new BroadcastChannel(CHANNEL_NAME)
    : null;

export function broadcastDatabaseSync(eventType: string): void {
  if (realtimeChannel) {
    try {
      realtimeChannel.postMessage({
        type: eventType,
        timestamp: new Date().toISOString(),
      });
    } catch {
      // ignore
    }
  }
}
